/**
 * Synchronous internal fallback generator with deterministic hashing
 */
export function generateFallbackReviewText(
  shopTitle: string,
  userSeed: string,
  starRating: 3 | 4 | 5 = 5
): string {
  const cleanTitle = shopTitle.trim();
  const lower = cleanTitle.toLowerCase();
  const rating = [3, 4, 5].includes(starRating) ? starRating : 5;

  let pool = GENERAL_5_STAR;

  if (
    lower.includes("spa") ||
    lower.includes("massage") ||
    lower.includes("thai") ||
    lower.includes("salon") ||
    lower.includes("wellness") ||
    lower.includes("therapy")
  ) {
    pool = rating === 5 ? SPA_5_STAR : rating === 4 ? SPA_4_STAR : SPA_3_STAR;
  } else if (
    lower.includes("cafe") ||
    lower.includes("coffee") ||
    lower.includes("food") ||
    lower.includes("restaurant")
  ) {
    pool = rating === 5 ? CAFE_5_STAR : rating === 4 ? CAFE_4_STAR : CAFE_3_STAR;
  } else {
    pool = rating === 5 ? GENERAL_5_STAR : rating === 4 ? GENERAL_4_STAR : GENERAL_3_STAR;
  }

  let hash = 0;
  const combined = `${userSeed}-${cleanTitle}-${rating}`;
  for (let i = 0; i < combined.length; i++) {
    hash = (hash << 5) - hash + combined.charCodeAt(i);
    hash |= 0;
  }

  const selectedIndex = Math.abs(hash) % pool.length;
  const rawTemplate = pool[selectedIndex].replace(/\{shop\}/g, cleanTitle);

  return humanizeReview(rawTemplate);
}

/**
 * Main review generator:
 * 1. Checks for Gemini API keys -> calls live Gemini Flash AI with lowercase/typo rules.
 * 2. If no API key or rate-limited -> seamlessly falls back to humanized template engine.
 */
export async function generateAiReviewText(
  shopTitle: string,
  userSeed: string,
  starRating: 3 | 4 | 5 = 5
): Promise<string> {
  try {
    const liveAiText = await fetchGeminiGeneratedReview(shopTitle, starRating);
    if (liveAiText) {
      return liveAiText;
    }
  } catch (err) {
    console.warn("Live Gemini review generation fallback:", err);
  }

  return generateFallbackReviewText(shopTitle, userSeed, starRating);
}
