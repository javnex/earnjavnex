/**
 * Dynamic AI Review Text Generator & Humanizer
 * Integrates Google Gemini Flash API with Multi-Key Rotation and Fallback Engine.
 * Formats reviews in casual Indian English with mobile typing quirks (lowercase start, subtle typos, no trailing period).
 * Supports length variety including ultra-short 2-4 word reviews.
 */

let currentKeyIndex = 0;

/**
 * Retrieves the next available Gemini API key from GEMINI_API_KEYS or GEMINI_API_KEY.
 * Supports comma-separated keys for automatic rotation and failover.
 */
export function getAvailableGeminiKeys(): string[] {
  const raw = process.env.GEMINI_API_KEYS || process.env.GEMINI_API_KEY || "";
  return raw
    .split(",")
    .map((k) => k.trim())
    .filter((k) => k.length > 5);
}

/**
 * Humanizes review text to emulate authentic mobile user typing on Google Maps:
 * - Lowercase first letter (like typing quickly on a phone)
 * - Removes stiff trailing period
 * - Subtle realistic quirks (e.g. 'definitly', 'recomended', '&')
 */
export function humanizeReview(text: string): string {
  let res = text.trim();

  // Strip leading/trailing quotation marks if generated by LLM
  res = res.replace(/^["'`]+|["'`]+$/g, "").trim();

  // 1. Lowercase starting letter (like casual mobile phone typing)
  if (res.length > 0) {
    res = res.charAt(0).toLowerCase() + res.slice(1);
  }

  // 2. Remove trailing period (mobile users rarely end short reviews with formal periods)
  if (res.endsWith(".")) {
    res = res.slice(0, -1);
  }

  // 3. Subtle human mobile typos/quirks
  const quirks: [RegExp, string][] = [
    [/\bdefinitely\b/gi, "definitly"],
    [/\brecommend\b/gi, "recomended"],
    [/\brecommended\b/gi, "recomended"],
    [/\bhygienic\b/gi, "hygenic"],
    [/\bexperience\b/gi, "experiance"],
    [/\b and \b/gi, " & "],
  ];

  // Apply at most 1 subtle quirk so it looks authentic and believable
  for (const [pattern, replacement] of quirks) {
    if (pattern.test(res)) {
      res = res.replace(pattern, replacement);
      break;
    }
  }

  return res.trim();
}

/**
 * Calls Gemini Flash REST API with automatic multi-key rotation and failover.
 * Generates natural Indian English reviews and enforces strict business category guardrails.
 */
async function fetchGeminiGeneratedReview(
  shopTitle: string,
  starRating: 3 | 4 | 5
): Promise<string | null> {
  const keys = getAvailableGeminiKeys();
  if (keys.length === 0) return null;

  const lower = shopTitle.toLowerCase();
  const isSpa =
    lower.includes("spa") ||
    lower.includes("thai") ||
    lower.includes("massage") ||
    lower.includes("salon") ||
    lower.includes("wellness") ||
    lower.includes("therapy") ||
    lower.includes("ayur") ||
    lower.includes("relax");

  const isFood =
    !isSpa &&
    (lower.includes("cafe") ||
      lower.includes("coffee") ||
      lower.includes("restaurant") ||
      lower.includes("bakery") ||
      lower.includes("dhaba") ||
      lower.includes("kitchen") ||
      lower.includes("pizza") ||
      lower.includes("food"));

  // Randomize length style:
  // 35% chance: Ultra-short (2 to 4 words)
  // 40% chance: Short Indian English (5 to 10 words)
  // 25% chance: Medium Indian English (11 to 18 words)
  const rand = Math.random();
  let lengthRule = "";
  if (rand < 0.35) {
    lengthRule = "STRICT LENGTH: Write ONLY 2 to 4 words. Examples: 'very good service', 'clean and peaceful place', 'loved the massage', 'average service ok ok', 'worth the money'.";
  } else if (rand < 0.75) {
    lengthRule = "STRICT LENGTH: Short Indian English, strictly 5 to 10 words. Everyday casual phrasing.";
  } else {
    lengthRule = "STRICT LENGTH: 11 to 18 words in casual Indian English mobile typing tone.";
  }

  let categoryRule = "";
  if (isSpa) {
    categoryRule = "BUSINESS TYPE: Spa, Massage & Relaxation Wellness Center. ABSOLUTE RULE: DO NOT mention food, restaurant, dinner, lunch, dishes, eating, or cooking! Focus ONLY on massage, therapists, relaxing vibe, cleanliness, jacuzzi, body relaxation, or staff behavior.";
  } else if (isFood) {
    categoryRule = "BUSINESS TYPE: Cafe / Restaurant. Focus on food taste, ambiance, seating, or staff service.";
  } else {
    categoryRule = "BUSINESS TYPE: General retail / service business. Focus on staff behavior, service quality, or overall experience.";
  }

  const prompt = `Write an authentic store review for '${shopTitle}'.
Rating: ${starRating} out of 5 stars.
${categoryRule}
${lengthRule}

MANDATORY RULES:
- Tone: Casual Indian English (natural everyday Indian phrasing, e.g. 'staff was very polite', 'clean & hygiene maintained', 'loved the service', 'worth the money', 'ok ok experience'). NOT formal US corporate English.
- Start with lowercase (no capital letter at the beginning).
- Absolutely NO corporate AI words (no 'epitome', 'tapestry', 'delve', 'moreover', 'testament', 'curated').
- Do NOT end with a period.
- Output ONLY the review text.`;

  // Try each key in sequence if one hits rate limits (HTTP 429)
  for (let attempt = 0; attempt < keys.length; attempt++) {
    const key = keys[(currentKeyIndex + attempt) % keys.length];
    const endpoint = `https://generativelanguage.googleapis.com/v1beta/models/gemini-flash-lite-latest:generateContent?key=${key}`;

    try {
      const response = await fetch(endpoint, {
        method: "POST",
        headers: { "Content-Type": "application/json" },
        body: JSON.stringify({
          contents: [{ parts: [{ text: prompt }] }],
          generationConfig: {
            temperature: 0.95,
            maxOutputTokens: 100,
          },
        }),
      });

      if (response.ok) {
        const data = await response.json();
        const candidate =
          data?.candidates?.[0]?.content?.parts?.[0]?.text?.trim();
        if (candidate) {
          // Advance rotation index for next request
          currentKeyIndex = (currentKeyIndex + attempt + 1) % keys.length;
          return humanizeReview(candidate);
        }
      } else {
        console.warn(`Gemini API key ${key.slice(0, 8)}... returned ${response.status}. Rotating...`);
      }
    } catch (err: any) {
      console.warn(`Gemini API fetch error on key ${key.slice(0, 8)}...:`, err.message);
    }
  }

  return null;
}

